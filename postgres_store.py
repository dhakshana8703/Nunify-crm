"""PostgreSQL connection for the CRM's existing database interface."""

import re
import sqlite3


# These inserts return their generated IDs to callers through the cursor.
GENERATED_IDS = frozenset({
    "accounts", "activities", "campaigns", "coverages", "credit_jobs", "handoffs",
    "people", "qualification_jobs", "sales_views", "scraper_api_requests", "scraper_intake_runs", "source_runs",
    "suppression", "tasks",
})
CRM_WRITER_LOCK = 721814336793914
INSERT = re.compile(r"^\s*INSERT\s+(OR\s+IGNORE\s+)?INTO\s+(\w+)", re.IGNORECASE)
WRITES = re.compile(r"^\s*(INSERT|UPDATE|DELETE|CREATE|ALTER|DROP|TRUNCATE)\b", re.IGNORECASE)
BIND = re.compile(
    r"""'(?:(?:'')|[^'])*'|"(?:(?:"")|[^"])*"|--[^\r\n]*|/\*[\s\S]*?\*/|\?|(?<!:):([a-zA-Z_]\w*)"""
)
JSON_PATH = re.compile(r"json_extract\(([\w.]+),\s*'\$\.([\w.]+)'\)", re.IGNORECASE)
JSON_ARROW = re.compile(r"([\w.]+)\s*->>", re.IGNORECASE)
JSON_ARRAY = re.compile(
    r"SELECT\s+value\s+FROM\s+json_each\((\?|:\w+)\)", re.IGNORECASE,
)
NOCASE_TYPE = re.compile(r"\bTEXT\b([^,\n]*?)\s+COLLATE\s+NOCASE\b", re.IGNORECASE)
NOCASE_SORT = re.compile(r"([\w.]+)\s+COLLATE\s+NOCASE\b", re.IGNORECASE)
INFO = re.compile(r"\s*PRAGMA table_info\((\w+)\)\s*", re.IGNORECASE)
INFO_QUERY = """
    SELECT ordinal_position - 1 AS cid, column_name AS name, data_type AS type
    FROM information_schema.columns
    WHERE table_schema = current_schema() AND table_name = ?
    ORDER BY ordinal_position
"""


def _postgres_sql(statement, *, bind, return_id=False):
    statement = statement.strip().rstrip(";")
    ddl = statement.upper().startswith(("CREATE ", "ALTER "))
    if ddl:
        statement = NOCASE_TYPE.sub(r"CITEXT\1", statement)
        statement = re.sub(r"\bINTEGER\b", "BIGINT", statement, flags=re.IGNORECASE)
        statement = re.sub(
            r"\bid\s+BIGINT\s+PRIMARY\s+KEY\b",
            "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", statement, flags=re.IGNORECASE,
        )
        statement = re.sub(r"^CREATE VIEW IF NOT EXISTS", "CREATE OR REPLACE VIEW", statement, flags=re.IGNORECASE)
    statement = NOCASE_SORT.sub(r"lower(\1)", statement)
    statement = re.sub(r"\s+COLLATE\s+NOCASE\b", "", statement, flags=re.IGNORECASE)
    statement = re.sub(r"\binstr\s*\(", "strpos(", statement, flags=re.IGNORECASE)
    statement = re.sub(r"\bIS\s+\?", "IS NOT DISTINCT FROM ?", statement, flags=re.IGNORECASE)
    statement = re.sub(r"\bIS\s+NOT\s+(excluded\.\w+|\d+)\b", r"IS DISTINCT FROM \1", statement, flags=re.IGNORECASE)
    statement = JSON_ARROW.sub(r"(\1)::jsonb ->>", statement)
    statement = JSON_ARRAY.sub(r"SELECT value::bigint FROM jsonb_array_elements_text((\1)::jsonb)", statement)

    def json_path(match):
        path = ", ".join(f"'{part}'" for part in match[2].split("."))
        return f"jsonb_extract_path_text(({match[1]})::jsonb, {path})"

    statement = JSON_PATH.sub(json_path, statement)
    insert = INSERT.match(statement)
    if insert and insert[1]:
        statement = INSERT.sub(r"INSERT INTO \2", statement, count=1) + " ON CONFLICT DO NOTHING"
    returning = bool(return_id and insert and insert[2].casefold() in GENERATED_IDS)
    if returning:
        statement += " RETURNING id"
    if bind:
        def placeholder(match):
            if match[0] == "?":
                return "%s"
            if match[1]:
                return f"%({match[1]})s"
            return match[0]

        statement = BIND.sub(placeholder, statement.replace("%", "%%"))
    return statement, returning


class Result:
    def __init__(self, cursor, returning=False):
        self._cursor = cursor
        self.rowcount = cursor.rowcount
        row = cursor.fetchone() if returning else None
        self.lastrowid = row[0] if row is not None else None

    def fetchone(self):
        return self._cursor.fetchone()

    def fetchall(self):
        return self._cursor.fetchall()

    def __iter__(self):
        return iter(self._cursor)


class PostgresConnection:
    dialect = "postgresql"

    def __init__(self, dsn, *, read_only=False):
        import psycopg2
        from psycopg2.extras import DictCursor

        self._driver = psycopg2
        self._read_only = read_only
        self._transaction = False
        try:
            self._connection = psycopg2.connect(dsn, cursor_factory=DictCursor, connect_timeout=10)
        except psycopg2.Error:
            raise sqlite3.OperationalError("Unable to connect to the CRM PostgreSQL database.") from None
        self._connection.autocommit = True
        self._run("SET lock_timeout = '15s'")
        if read_only:
            self._run("SET default_transaction_read_only = on")

    def _run(self, statement, params=None, *, many=False):
        cursor = self._connection.cursor()
        try:
            if many:
                cursor.executemany(statement, params)
            elif params is None:
                cursor.execute(statement)
            else:
                cursor.execute(statement, params)
        except self._driver.Error as error:
            cursor.close()
            code = error.pgcode or "connection error"
            if isinstance(error, self._driver.IntegrityError):
                failure = sqlite3.IntegrityError(f"PostgreSQL constraint violation ({code}).")
                failure.sqlite_errorcode = (
                    sqlite3.SQLITE_CONSTRAINT_UNIQUE if code == "23505" else sqlite3.SQLITE_CONSTRAINT
                )
            else:
                failure = sqlite3.OperationalError(f"PostgreSQL {type(error).__name__} ({code}).")
                if code in {"55P03", "40001", "40P01"}:
                    failure.sqlite_errorcode = sqlite3.SQLITE_BUSY
            raise failure from None
        return cursor

    def _begin(self):
        if self._transaction:
            raise sqlite3.OperationalError("Cannot begin a nested CRM transaction.")
        self._run("BEGIN").close()
        self._transaction = True
        try:
            if not self._read_only:
                self._run(f"SELECT pg_advisory_xact_lock({CRM_WRITER_LOCK})").close()
        except sqlite3.Error:
            self.rollback()
            raise

    def execute(self, statement, params=None):
        if statement.strip().upper() in {"BEGIN", "BEGIN IMMEDIATE"}:
            self._begin()
            return None
        info = INFO.fullmatch(statement)
        if info:
            statement, params = INFO_QUERY, (info[1],)
        sql, returning = _postgres_sql(statement, bind=params is not None, return_id=True)
        if WRITES.match(sql) and not self._transaction:
            self._begin()
        return Result(self._run(sql, params), returning)

    def executemany(self, statement, params):
        sql, _returning = _postgres_sql(statement, bind=True)
        if WRITES.match(sql) and not self._transaction:
            self._begin()
        return Result(self._run(sql, params, many=True))

    def executescript(self, script):
        with self:
            for statement in script.split(";"):
                if statement.strip():
                    self.execute(statement)

    def commit(self):
        if self._transaction:
            self._run("COMMIT").close()
            self._transaction = False

    def rollback(self):
        if self._transaction:
            try:
                self._run("ROLLBACK").close()
            finally:
                self._transaction = False

    def close(self):
        self._connection.close()

    def __enter__(self):
        return self

    def __exit__(self, error_type, _error, _traceback):
        if error_type:
            self.rollback()
        else:
            try:
                self.commit()
            except sqlite3.Error:
                self.rollback()
                raise
